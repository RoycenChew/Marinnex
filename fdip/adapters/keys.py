"""API keys and sessions.

The key rule (CLAUDE.md 2.12) is that the raw key is never stored. What is
stored is `HMAC-SHA256(server_pepper, secret)`, compared in constant time, and
the key itself is returned exactly once at creation. The consequences are worth
stating because they look like bugs otherwise: a lost key cannot be recovered,
only replaced, and a database dump cannot be replayed against the API.

HMAC with a pepper rather than argon2 here, and argon2 for passwords. The two
cases differ: a password is low-entropy and chosen by a human, so it needs a slow
hash; an API key is 240 random bits generated by us, so there is nothing to brute
force and a slow hash would only add latency to every request. The pepper is what
makes the stored digest useless on its own.
"""
from __future__ import annotations

import hashlib
import hmac
import secrets
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from typing import Any

from itsdangerous import BadSignature, SignatureExpired, URLSafeTimedSerializer

LIVE_PREFIX = "fdip_live_"
TEST_PREFIX = "fdip_test_"
_SECRET_BYTES = 30
PREFIX_LENGTH = 18
"""How much of the key is stored in clear for lookup: the scheme prefix plus the
first eight characters of the secret. Enough to find one row, far too little to
reconstruct the key."""

SESSION_COOKIE = "fdip_session"
SESSION_MAX_AGE = int(timedelta(days=14).total_seconds())


@dataclass(frozen=True)
class IssuedKey:
    """What key creation returns. `secret` is shown once and then unavailable."""

    key_id: str
    prefix: str
    key_hash: str
    secret: str
    mode: str


def _hash(pepper: str, secret: str) -> str:
    return hmac.new(
        pepper.encode("utf-8"), secret.encode("utf-8"), hashlib.sha256
    ).hexdigest()


def generate_key(mode: str, pepper: str, key_id: str) -> IssuedKey:
    if mode not in ("live", "test"):
        raise ValueError("mode must be live or test")
    scheme = LIVE_PREFIX if mode == "live" else TEST_PREFIX
    secret = secrets.token_urlsafe(_SECRET_BYTES)
    full = scheme + secret
    return IssuedKey(
        key_id=key_id,
        prefix=full[:PREFIX_LENGTH],
        key_hash=_hash(pepper, full),
        secret=full,
        mode=mode,
    )


def key_prefix(presented: str) -> str:
    return presented.strip()[:PREFIX_LENGTH]


def verify_key(presented: str, stored_hash: str, pepper: str) -> bool:
    """Constant time, so a timing difference cannot leak the stored digest."""
    return hmac.compare_digest(_hash(pepper, presented.strip()), stored_hash)


def key_mode(presented: str) -> str | None:
    text = presented.strip()
    if text.startswith(LIVE_PREFIX):
        return "live"
    if text.startswith(TEST_PREFIX):
        return "test"
    return None


def is_expired(expires_at: datetime | None, when: datetime | None = None) -> bool:
    if expires_at is None:
        return False
    moment = when or datetime.now(UTC).replace(tzinfo=None)
    return expires_at <= moment


# -- passwords ------------------------------------------------------------

def _password_context() -> Any:
    from passlib.context import CryptContext

    return CryptContext(schemes=["argon2"], deprecated="auto")


MIN_PASSWORD_LENGTH = 8


def hash_password(password: str, enforce_policy: bool = True) -> str:
    """Argon2. `enforce_policy=False` is for the seeded dev account only.

    The length rule is a *registration* policy, not a property of hashing, and the
    dev account's password is fixed by the brief at seven characters. Putting the
    check here and then bypassing it for one caller is better than dropping it:
    the public route still enforces it, and the one exception is named.
    """
    if enforce_policy and len(password) < MIN_PASSWORD_LENGTH:
        raise ValueError(
            "password must be at least %d characters" % MIN_PASSWORD_LENGTH
        )
    return str(_password_context().hash(password))


def verify_password(password: str, stored_hash: str) -> bool:
    try:
        return bool(_password_context().verify(password, stored_hash))
    except Exception:
        # A malformed stored hash is a failed login, not a 500. Returning False
        # keeps an unparseable row from locking the whole login route.
        return False


# -- sessions -------------------------------------------------------------

def session_token(secret: str, user_id: str) -> str:
    return str(URLSafeTimedSerializer(secret, salt="fdip-session").dumps(user_id))


def read_session(secret: str, token: str,
                 max_age: int = SESSION_MAX_AGE) -> str | None:
    try:
        return str(
            URLSafeTimedSerializer(secret, salt="fdip-session")
            .loads(token, max_age=max_age)
        )
    except (BadSignature, SignatureExpired):
        return None


