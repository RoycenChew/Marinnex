#!/usr/bin/env bash
# Write /srv/marinnex/.env from SSM Parameter Store.
#
# Every parameter under /marinnex/prod becomes one line. Values are never
# echoed, never passed as arguments, and the file is written 600 before
# anything is put in it — a world-readable moment between create and chmod is
# all it would take.
set -euo pipefail

PREFIX="${SSM_PREFIX:-/marinnex/prod}"
TARGET="${ENV_FILE:-/srv/marinnex/.env}"
REGION="${AWS_REGION:-ap-southeast-5}"

umask 077
TMP="$(mktemp "${TARGET}.XXXXXX")"
trap 'rm -f "$TMP"' EXIT

echo "# Generated by fetch-secrets.sh from ${PREFIX}. Do not edit by hand." > "$TMP"
echo "# $(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$TMP"

count=0
while IFS=$'\t' read -r name value; do
    [ -n "$name" ] || continue
    # /marinnex/prod/FDIP_KEY_PEPPER -> FDIP_KEY_PEPPER
    key="${name##*/}"
    # Quote the value and escape any quote inside it, so a secret containing a
    # space or a '#' survives being read back by docker compose.
    escaped="${value//\"/\\\"}"
    printf '%s="%s"\n' "$key" "$escaped" >> "$TMP"
    count=$((count + 1))
done < <(
    aws ssm get-parameters-by-path \
        --path "$PREFIX" \
        --with-decryption \
        --recursive \
        --region "$REGION" \
        --query 'Parameters[].[Name,Value]' \
        --output text
)

if [ "$count" -eq 0 ]; then
    echo "fetch-secrets: no parameters found under ${PREFIX}" >&2
    exit 1
fi

mv "$TMP" "$TARGET"
chmod 600 "$TARGET"
trap - EXIT
# The count, never the names of the secrets or their values.
echo "fetch-secrets: wrote ${count} variables to ${TARGET}"
