"""Structural guarantees: the ones a reviewer cannot check by reading.

These four tests each pin a rule that is cheap to break by accident and
expensive to discover later: the domain layer staying framework-free, every
project-scoped table refusing an unscoped query, the migration agreeing with the
table definitions, and `openapi.json` not being stale.
"""
from __future__ import annotations

import ast
import json
from pathlib import Path
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parent.parent
DOMAIN = ROOT / "fdip" / "domain"

FORBIDDEN_IN_DOMAIN = (
    "fastapi", "starlette", "sqlalchemy", "alembic", "pydantic", "uvicorn",
    "httpx", "openpyxl", "pypdfium2", "passlib",
)
"""The domain layer is pure (7.1). The moment a validator imports a request
object, the rule stops being testable without a server."""


def _imports(path: Path) -> set[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    found: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            found.add(node.module.split(".")[0])
    return found


def test_the_domain_layer_imports_no_framework() -> None:
    offenders: dict[str, list[str]] = {}
    for path in sorted(DOMAIN.glob("*.py")):
        bad = sorted(_imports(path) & set(FORBIDDEN_IN_DOMAIN))
        if bad:
            offenders[path.name] = bad
    assert not offenders, offenders


def test_the_domain_layer_imports_no_adapter_or_api_module() -> None:
    """It may use the toolkit, but nothing that touches a socket or a database."""
    offenders: dict[str, list[str]] = {}
    for path in sorted(DOMAIN.glob("*.py")):
        text = path.read_text(encoding="utf-8")
        bad = [
            needle for needle in ("fdip.adapters", "fdip.api", "fdip.pipeline",
                                  "fdip.worker")
            if needle in text
        ]
        if bad:
            offenders[path.name] = bad
    assert not offenders, offenders


def test_every_project_scoped_table_refuses_an_unscoped_query() -> None:
    """The rule from 3.7, checked against every table rather than a sample."""
    from fdip.adapters.repository import UnscopedQuery, scoped
    from fdip.adapters.tables import GLOBAL_TABLES, PROJECT_SCOPED

    assert len(PROJECT_SCOPED) == 18, "21 tables, 3 of them global"
    for table in PROJECT_SCOPED:
        assert "project_id" in table.c, table.name
        for empty in (None, ""):
            with pytest.raises(UnscopedQuery):
                scoped(table, empty)
        # With a project, the predicate is actually in the statement.
        statement = str(scoped(table, "prj_1").compile(
            compile_kwargs={"literal_binds": True}
        ))
        assert "project_id = 'prj_1'" in statement, table.name

    # The three global tables are global for a stated reason, not by omission.
    assert {"users", "projects", "schema_templates"} == GLOBAL_TABLES


def test_a_repository_cannot_be_built_without_a_project() -> None:
    from fdip.adapters.repository import ProjectRepository, UnscopedQuery

    for empty in (None, ""):
        with pytest.raises(UnscopedQuery):
            ProjectRepository(None, empty)  # type: ignore[arg-type]


def test_the_migration_and_the_table_definitions_agree(tmp_path: Path) -> None:
    """Migration 001 is autogenerated, and this is what keeps it honest.

    Both schemas are built into separate SQLite files and compared column by
    column. A drift here means a deployment has a different database than the
    tests ran against, which is the kind of bug that only shows in production.
    """
    import subprocess
    import sys

    from sqlalchemy import create_engine, inspect

    from fdip.adapters.db import create_all

    direct_path = tmp_path / "direct.db"
    direct = create_engine("sqlite:///" + str(direct_path))
    create_all(direct)

    migrated_path = tmp_path / "migrated.db"
    completed = subprocess.run(
        [sys.executable, "-m", "alembic", "upgrade", "head"],
        cwd=str(ROOT),
        env={
            **_clean_env(),
            "FDIP_DB_URL": "sqlite:///" + str(migrated_path),
            "FDIP_DATA_DIR": str(tmp_path),
            "FDIP_PROVIDER_MODE": "mock",
        },
        capture_output=True, text=True, timeout=180,
    )
    assert completed.returncode == 0, completed.stderr
    migrated = create_engine("sqlite:///" + str(migrated_path))

    def describe(engine: Any) -> dict[str, dict[str, str]]:
        inspector = inspect(engine)
        return {
            name: {
                column["name"]: str(column["type"])
                for column in inspector.get_columns(name)
            }
            for name in sorted(inspector.get_table_names())
            if name != "alembic_version"
        }

    expected = describe(direct)
    actual = describe(migrated)
    assert set(actual) == set(expected), {
        "only_in_migration": sorted(set(actual) - set(expected)),
        "only_in_tables": sorted(set(expected) - set(actual)),
    }
    for name in expected:
        assert actual[name] == expected[name], name
    assert len(expected) == 21, len(expected)
    direct.dispose()
    migrated.dispose()


def _clean_env() -> dict[str, str]:
    import os

    return {
        key: value for key, value in os.environ.items()
        if not key.startswith("FDIP_")
    }


def test_openapi_json_is_not_stale() -> None:
    """`fdip/openapi.json` is what the UI agent reads, so it must match the app.

    Regenerate with `fdip openapi --out openapi.json` when a route changes.
    """
    from fdip.api.app import openapi_document

    path = ROOT / "openapi.json"
    assert path.is_file(), (
        "openapi.json is missing; run: fdip openapi --out openapi.json"
    )
    committed = json.loads(path.read_text(encoding="utf-8"))
    current = openapi_document()
    if committed != current:
        missing = sorted(set(current["paths"]) - set(committed.get("paths", {})))
        extra = sorted(set(committed.get("paths", {})) - set(current["paths"]))
        raise AssertionError(
            "openapi.json is stale; run: fdip openapi --out openapi.json\n"
            "paths only in the app: %s\npaths only in the file: %s"
            % (missing, extra)
        )


def test_the_contract_covers_every_published_route() -> None:
    """Every `/v1` route the app serves is in `API_CONTRACT_FOR_UI.md`.

    A contract that silently omits a route is how the UI agent ends up guessing.
    """
    import re

    from fdip.api.app import openapi_document

    path = ROOT / "docs" / "API_CONTRACT_FOR_UI.md"
    assert path.is_file(), "API_CONTRACT_FOR_UI.md is missing"

    def shape(route: str) -> str:
        """Route with its parameter names flattened.

        The contract writes `{id}` where OpenAPI writes `{document_id}`, which is
        clearer for a reader and means the same route. Comparing the spelling
        would make the test about prose rather than coverage.
        """
        return re.sub(r"\{[^}]*\}", "{}", route.replace("/v1", ""))

    documented = {shape(match) for match in re.findall(
        r"/(?:v1/)?[a-z0-9\-{}/_]+", path.read_text(encoding="utf-8")
    )}
    undocumented = sorted(
        route for route in openapi_document()["paths"]
        if shape(route) not in documented
    )
    assert not undocumented, undocumented


def test_the_captured_examples_are_usable_as_ui_mocks() -> None:
    """`samples/examples.json` is what `VITE_USE_MOCKS=true` reads.

    The UI agent builds against this file before the backend is running, so its
    shape is part of the contract: a flat map of `"<METHOD> /v1/<path>"` to
    `{status, body}`. It must also contain the two responses the UI has special
    rendering for -- a scan and an error -- because the UI cannot mock what it has
    never seen.
    """
    path = ROOT / "samples" / "examples.json"
    assert path.is_file(), "regenerate with: pytest tests/test_capture_examples.py"
    examples = json.loads(path.read_text(encoding="utf-8"))
    assert len(examples) >= 20, len(examples)

    for key, entry in examples.items():
        assert isinstance(entry, dict), key
        assert set(entry) == {"status", "body"}, (key, sorted(entry))
        assert isinstance(entry["status"], int), key
        method = key.split(" ", 1)[0]
        assert method in ("GET", "POST", "DELETE"), key
        assert "/v1/" in key, key

    scan = next(k for k in examples if "a scan" in k)
    body = examples[scan]["body"]
    assert body["status"] == "needs_review"
    assert "scanned_document_review" in body["reasons"]

    error = next(k for k in examples if "error" in k)
    assert examples[error]["status"] == 404
    assert examples[error]["body"]["code"] == "not_found"


def test_the_contract_states_the_two_ui_renderings() -> None:
    """The scan banner and "Not on document" are behaviour the UI must match.

    Pinned here because they are the two places the UI can look correct while being
    wrong: a scan rendered as an error alarms the user over normal behaviour, and an
    absent field rendered as `0` is a fabricated number on a financial document.
    """
    text = (ROOT / "docs" / "API_CONTRACT_FOR_UI.md").read_text(encoding="utf-8")
    for needle in (
        "scanned_document_review",
        "Scanned documents are reviewed by a person before acceptance",
        "Not on document",
        "VITE_USE_MOCKS=true",
        "samples/examples.json",
        "README_RUN.md",
    ):
        assert needle in text, needle
    # The cap keeps this document something a UI author will actually read end to
    # end. 200 -> 210 for `field-reviews`, 210 -> 225 for custom schemas, which
    # add two routes and a paragraph an integrator cannot work without: aliases
    # change the keys they receive. Trim before raising it again.
    assert len(text.splitlines()) < 225, len(text.splitlines())
